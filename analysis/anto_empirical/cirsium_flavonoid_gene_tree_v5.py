# Frozen publication-selected source transcripts; putative isoforms i5 and
# i7 are tested as alternative samples, not two independent locus origins.
CASES={
    "DFR_ANR_primary":{
        "source":(
            "TR35526|c0_g1_i1","TR38875|c0_g4_i5",
            "TR39766|c0_g1_i2"
        ),
        "positive":"DFR_reference",
        "related":"ANR_negative_control"
    },
    "DFR_ANR_alt_isoform":{
        "source":(
            "TR35526|c0_g1_i1","TR38875|c0_g4_i7",
            "TR39766|c0_g1_i2"
        ),
        "positive":"DFR_reference",
        "related":"ANR_negative_control"
    },
    "ANS_FLS":{
        "source":("TR58302|c0_g1_i1",),
        "positive":"ANS_reference",
        "related":"FLS_negative_control"
    }
}

REFERENCE_PROVENANCE_VERSION="aza3_flavonoid_family_reference_panel_v5"
SOURCE_PROVENANCE_VERSION="anto_park2020_26_source_transcripts_v6"
MIN_OVERLAP_AA=60
TREE_BOOTSTRAP_REPLICATES=200
BOOTSTRAP_SEED=20261019
ALL_AA=set("ACDEFGHIKLMNPQRSTVWYX")


def load_sources(fasta_file,provenance_file):
    meta=json.loads(Path(provenance_file).read_text(encoding="utf-8"))
    if meta.get("contract")!=SOURCE_PROVENANCE_VERSION:
        raise ValueError("Unexpected source RNA assembly accession contract")
    dna=read_fasta(fasta_file)
    records=meta.get("records",[])
    if len(records)!=26 or len(dna)!=26 or set(dna)!={r["id"] for r in records}:
        raise ValueError("Source RNA transcript inventory not the audited 26")
    for r in records:
        seq=dna[r["id"]]
        if len(seq)!=r["source_fasta_length"] or sha256(
                seq.encode("ascii")).hexdigest()!=r["sha256_nucleotide"]:
            raise ValueError("Original 2020 Cirsium nucleotide sequence damaged")
    return dna,meta


def load_reference_proteins(fasta_file,provenance_file):
    meta=json.loads(Path(provenance_file).read_text(encoding="utf-8"))
    if meta.get("version")!=REFERENCE_PROVENANCE_VERSION or meta.get("n_reference_records")!=9:
        raise ValueError("Unexpected nine-protein accession panel")
    fasta=read_fasta(fasta_file)
    if len(fasta)!=9 or len(meta.get("reference_proteins",[]))!=9:
        raise ValueError("Exactly 9 curated reference proteins required")
    out={}
    ids=set()
    for r in meta["reference_proteins"]:
        if r["accession"] in ids:
            raise ValueError("Duplicate reference accession")
        ids.add(r["accession"])
        name=f'{r["accession"]}|{r["group"]}|{r["taxon"].replace(" ","_")}'
        if name not in fasta:
            raise ValueError("Reference name/version mismatch")
        aa=fasta[name]
        if len(aa)!=r["length_aa"] or any(x not in ALL_AA for x in aa):
            raise ValueError("Reference amino acid record invalid")
        out[r["accession"]]={**r,"protein":aa}
    expected={"DFR_reference":3,"ANR_negative_control":2,
              "ANS_reference":2,"FLS_negative_control":2}
    if Counter(x["group"] for x in out.values())!=expected:
        raise ValueError("Protein reference enzyme-family composition changed")
    return out


def chosen_source_peptide(dna, family_references):
    """Find stop-delimited ORF fragment maximizing normalized protein score.

    The positive and related-family references BOTH compete; no DFR/ANS
    orthology is assumed when deciding the translated orientation/frame.
    """
    aln=_aligner()
    candidates=list(six_frame_segments(dna))
    if not candidates:
        raise ValueError("No 35-aa translated segment in frozen source")
    chosen=None
    for segment in candidates:
        for r in family_references:
            z=alignment_summary(r["protein"],segment["aa_segment"],aln)
            score=(z["normalized_alignment_score"],z["aligned_aa"],
                   segment["segment_length_aa"])
            if chosen is None or score>chosen["key"]:
                chosen={
                    "key":score,
                    "protein":segment["aa_segment"],
                    "aa_segment_length":segment["segment_length_aa"],
                    "read_orientation":segment["strand"],
                    "frame":segment["reading_frame"],
                    "score_reference_accession":r["accession"],
                    "alignment_identity_vs_best_reference":z["aligned_identity"],
                    "alignment_reference_coverage":z["reference_coverage"],
                }
    assert chosen is not None
    if chosen["aa_segment_length"]<80:
        raise ValueError("Focal source peptide too short for exploratory tree")
    chosen.pop("key")
    return chosen


def safe_name(prefix,raw):
    out=prefix+"_"+re.sub(r"[^A-Za-z0-9_]","_",raw)
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]+",out):
        raise ValueError("Unsafe tree identifier")
    return out


def source_alignment_input(case,sources,references):
    opts=CASES[case]
    family={opts["positive"],opts["related"]}
    selected=[r for r in references.values() if r["group"] in family]
    selected=sorted(selected,key=lambda r:r["accession"])
    records=[]
    meta={}
    for r in selected:
        identifier=safe_name("REF",r["accession"])
        records.append(SeqRecord(Seq(r["protein"]),id=identifier,description=""))
        meta[identifier]={
            "is_reference":True,"accession":r["accession"],
            "family":r["group"],"taxon":r["taxon"],
        }
    for ident in opts["source"]:
        if ident not in sources:
            raise ValueError(f"Focal source transcript missing: {ident}")
        row=chosen_source_peptide(sources[ident],selected)
        identifier=safe_name("CJ",ident)
        records.append(SeqRecord(Seq(row["protein"]),id=identifier,description=""))
        meta[identifier]={
            "is_reference":False,
            "source_id":ident,
            "assembly_group":ident.rsplit("_i",1)[0],
            **{k:v for k,v in row.items() if k!="protein"}
        }
    if len(meta)!=len(records):
        raise ValueError("Duplicated taxon naming")
    if len(opts["source"])!=len(set(ident.rsplit("_i",1)[0] for ident in opts["source"])):
        raise ValueError("Repeated assembly group within one tree")
    return records,meta


def run_mafft(records, timeout=120):
    """Run --auto MAFFT from known source proteins; fail if aligner unavailable."""
    with tempfile.TemporaryDirectory() as folder:
        src=Path(folder)/"unaligned.fasta"
        SeqIO.write(records,src,"fasta")
        try:
            done=subprocess.run(
                ["mafft","--auto","--quiet",str(src)],
                capture_output=True,text=True,check=True,timeout=timeout)
        except (FileNotFoundError,subprocess.CalledProcessError,
                subprocess.TimeoutExpired) as e:
            raise RuntimeError("MAFFT unavailable or alignment failed; no gene-tree inference authorized") from e
        seqs=list(SeqIO.parse(StringIO(done.stdout),"fasta"))
        if len(seqs)!=len(records) or {x.id for x in seqs}!={x.id for x in records}:
            raise ValueError("MAFFT discarded, duplicated or relabeled a protein")
        seqmap={r.id:str(r.seq).upper() for r in seqs}
        lengths={len(s) for s in seqmap.values()}
        if len(lengths)!=1 or any(not set(s)<=ALL_AA|{"-"} for s in seqmap.values()):
            raise ValueError("Invalid MAFFT amino acid alignment")
        if next(iter(lengths))<100:
            raise ValueError("Resulting protein alignment too short")
        return seqmap,done.stdout


def _pairwise_p_distance(seq1,seq2,columns=None):
    if len(seq1)!=len(seq2):
        raise ValueError("Aligned sequences must share column count")
    indices=range(len(seq1)) if columns is None else columns
    compared=different=0
    for i in indices:
        x,y=seq1[i],seq2[i]
        if x in "-X" or y in "-X":continue
        compared+=1
        different+=(x!=y)
    if compared<MIN_OVERLAP_AA:
        raise ValueError("Protein alignment has insufficient shared nongap residues")
    return different/compared,compared


def distance_matrix(aligned,columns=None):
    ids=sorted(aligned)
    values=[]
    compared=[]
    for i,id1 in enumerate(ids):
        row=[]
        for j in range(i):
            d,sites=_pairwise_p_distance(aligned[id1],aligned[ids[j]],columns)
            row.append(d)
            compared.append(sites)
        row.append(0.)
        values.append(row)
    return DistanceMatrix(ids,values),min(compared),max(compared)


def unrooted_family_split(tree,query_id,positives,negatives):
    """Unrooted bipartition classification, *not* orthology posterior.

    Return reference family side (positive/related), an intermediate branch
    if both separating splits exist, or INTERMIXED if there is no branch that
    separates every positive from every related reference. Rooting-independent.
    """
    all_leaves={tip.name for tip in tree.get_terminals()}
    positive,related=set(positives),set(negatives)
    if not positive or not related or query_id not in all_leaves:
        raise ValueError("Missing predeclared candidate/reference leaves")
    if positive&related or not positive<=all_leaves or not related<=all_leaves:
        raise ValueError("Ambiguous positive vs negative reference sets")
    if query_id in positive|related:
        raise ValueError("Query must not be an anchor")
    compatible=set()
    for clade in tree.get_nonterminals():
        inside={tip.name for tip in clade.get_terminals()}
        outside=all_leaves-inside
        if positive<=inside and related<=outside:
            compatible.add("POSITIVE" if query_id in inside else "RELATED")
        if positive<=outside and related<=inside:
            compatible.add("POSITIVE" if query_id in outside else "RELATED")
    # terminal edges also matter for small trees (e.g. only one query).
    if compatible=={"POSITIVE"}:return "POSITIVE_FAMILY_SIDE"
    if compatible=={"RELATED"}:return "RELATED_FAMILY_SIDE"
    if compatible=={"POSITIVE","RELATED"}:return "BETWEEN_FAMILY_ANCHORS"
    return "REFERENCE_FAMILIES_NOT_SEPARATED"


def bootstrap_family_support(aligned,meta,positive_group,related_group,
                             replicates=TREE_BOOTSTRAP_REPLICATES,
                             seed=BOOTSTRAP_SEED):
    if not isinstance(replicates,int) or replicates<1:
        raise ValueError("Bootstrap replicate count must be positive")
    rng=Random(seed)
    reference_positive={k for k,v in meta.items() if v["is_reference"] and v["family"]==positive_group}
    reference_related={k for k,v in meta.items() if v["is_reference"] and v["family"]==related_group}
    queries=[k for k,v in meta.items() if not v["is_reference"]]
    if len(reference_positive)<2 or len(reference_related)<2:
        raise ValueError("At least two independent reference taxa per family")
    dm,site_min,site_max=distance_matrix(aligned)
    tree=DistanceTreeConstructor().nj(dm)
    original={
        q:unrooted_family_split(tree,q,reference_positive,reference_related)
        for q in queries}
    counts={q:Counter() for q in queries}
    ninvalid=0
    L=len(next(iter(aligned.values())))
    for _ in range(replicates):
        columns=[rng.randrange(L) for _ in range(L)]
        try:
            dm,_,_=distance_matrix(aligned,columns)
        except ValueError:
            ninvalid+=1
            continue
        t=DistanceTreeConstructor().nj(dm)
        for q in queries:
            counts[q][unrooted_family_split(t,q,reference_positive,reference_related)]+=1
    good=replicates-ninvalid
    if good<max(1,(replicates+1)//2):
        raise ValueError("Too many bootstrap site resamples lacked meaningful protein overlap")
    reports={}
    for q in queries:
        reports[q]={
            "observed_unrooted_NJ_family_split":original[q],
            "bootstrap_counts":dict(counts[q]),
            "bootstrap_valid_replicates":good,
            "bootstrap_invalid_replicates":ninvalid,
            "bootstrap_positive_side_fraction":counts[q]["POSITIVE_FAMILY_SIDE"]/good,
            "bootstrap_related_side_fraction":counts[q]["RELATED_FAMILY_SIDE"]/good,
            "bootstrap_between_or_interleaved_fraction":
                (counts[q]["BETWEEN_FAMILY_ANCHORS"]+
                 counts[q]["REFERENCE_FAMILIES_NOT_SEPARATED"])/good,
            "no_orthology_or_function_inference":True,
        }
    output=StringIO()
    Phylo.write(tree,output,"newick")
    return {
        "queries":reports,
        "unrooted_neighbor_joining_newick":output.getvalue().strip(),
        "alignment_length_aa":L,
        "min_observed_shared_sites_across_pairs":site_min,
        "max_observed_shared_sites_across_pairs":site_max,
        "bootstrap_site_replicates_requested":replicates,
    }


def run_panel(source_fasta,source_provenance,reference_fasta,
              reference_provenance,bootstraps=TREE_BOOTSTRAP_REPLICATES):
    source,source_meta=load_sources(source_fasta,source_provenance)
    references=load_reference_proteins(reference_fasta,reference_provenance)
    output={}
    alignments={}
    for case in CASES:
        records,meta=source_alignment_input(case,source,references)
        aligned,fasta=run_mafft(records)
        design=CASES[case]
        assessed=bootstrap_family_support(
            aligned,meta,design["positive"],design["related"],
            replicates=bootstraps,seed=BOOTSTRAP_SEED)
        output[case]={
            "positive_family":design["positive"],
            "related_family":design["related"],
            "source_transcripts":list(design["source"]),
            "reference_accessions":[meta[x]["accession"] for x in meta if meta[x]["is_reference"]],
            "source_translation":{
                x:meta[x] for x in meta if not meta[x]["is_reference"]
            },
            **assessed,
        }
        alignments[case]=fasta
    return {
        "analysis_version":"aza3_cirsium_2020_protein_family_phylogeny_v5",
        "source_study":"Park 2020 Cirsium japonicum publisher 26 audited unigene transcripts",
        "source_ryukyu_2026_sequences_included":False,
        "reference_panel_size":len(references),
        "three_independent_tree_configurations":len(output),
        "conditions":"MAFFT multiple protein alignment; unrooted NJ with amino-acid p-distance on overlapping sites; nonparametric site-bootstrap; no genetic orthology or enzyme-function claim",
        "trees":output,
        "phylogenetic_orthology_established":False,
        "molecular_phenotype_reexpression_demonstrated":False,
        "source_alignments":alignments,
    }


def main():
    root=Path(__file__).resolve().parents[2]
    data=root/"data/anto_source_handoff/molecular"
    ap=argparse.ArgumentParser()
    ap.add_argument("--source-fasta",type=Path,default=data/"cirsium_japonicum_2020_26_source_sequences_v6.fasta")
    ap.add_argument("--source-provenance",type=Path,default=data/"cirsium_japonicum_2020_26_sequence_provenance_v6.json")
    ap.add_argument("--reference-fasta",type=Path,default=data/"DFR_ANR_ANS_FLS_reference_proteins_v5.fasta")
    ap.add_argument("--reference-provenance",type=Path,default=data/"DFR_ANR_ANS_FLS_reference_provenance_v5.json")
    ap.add_argument("--bootstraps",type=int,default=TREE_BOOTSTRAP_REPLICATES)
    ap.add_argument("--output",type=Path)
    ap.add_argument("--alignment-directory",type=Path)
    args=ap.parse_args()
    outcome=run_panel(
        args.source_fasta,args.source_provenance,
        args.reference_fasta,args.reference_provenance,
        bootstraps=args.bootstraps)
    fasta=outcome.pop("source_alignments")
    if args.alignment_directory:
        args.alignment_directory.mkdir(parents=True,exist_ok=True)
        for name,aligned in fasta.items():
            (args.alignment_directory/(name+".fasta")).write_text(aligned,encoding="utf-8")
            (args.alignment_directory/(name+".nwk")).write_text(
                outcome["trees"][name]["unrooted_neighbor_joining_newick"]+"\n",encoding="utf-8")
    if args.output:
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(json.dumps(outcome,indent=2,sort_keys=True,ensure_ascii=False)+"\n",encoding="utf-8")
    print("TREE_RESULT_SUMMARY_JSON:"+json.dumps({
        "version":outcome["analysis_version"],
        "tree_scenarios":list(outcome["trees"]),
        "reference_n":outcome["reference_panel_size"],
        "reexpression":outcome["molecular_phenotype_reexpression_demonstrated"],
    },separators=(",",":")))
    for case,report in outcome["trees"].items():
        for q,results in report["queries"].items():
            print("TREE_QUERY_JSON:"+json.dumps({
                "case":case,
                "source_id":report["source_translation"][q]["source_id"],
                "source_peptide_aa":report["source_translation"][q]["aa_segment_length"],
                "reading_frame":report["source_translation"][q]["frame"],
                "orientation":report["source_translation"][q]["read_orientation"],
                "alignment_length_aa":report["alignment_length_aa"],
                "observed_shared_sites_min":report["min_observed_shared_sites_across_pairs"],
                **results
            },separators=(",",":")))
    return outcome


if __name__=="__main__":
    main()
