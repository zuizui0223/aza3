"""Exploratory within-flavonoid-family gene-tree screen (Cirsium source 2020).

CRITICAL SCOPE: This is a gene-FAMILY topology/partial-protein alignment
experiment. It is NOT validated orthology, protein catalytic specificity,
anthocyanin restoration, genomic lineage history, or the 2026 Ryukyu pair.

Candidate sequences: 5 source-verified Park-2020 Cirsium japonicum
transcripts (in 4 source assembly groups), with 2 candidate isoforms
from the same group evaluated as alternate analyses, never independent
species or independent origins.

References: 3 DFR + 2 ANR and separately 2 ANS + 2 FLS accession-verified
proteins. Never align the evolutionarily unrelated DFR/ANR and ANS/FLS
enzyme superfamilies together as one meaningful gene tree.

The alignment is generated by MAFFT (external dependency in aza3 CI).
The tree is unrooted neighbor-joining on pairwise nongap amino-acid
p-distances, with nonparametric SITE bootstrap support for a family-
separating unrooted branch. No DNA codon position, demographic tree,
species tree or molecular clock can be estimated from these data.

A source-query topology placed on a DFR/ANS side of a reference branch
is only a nearest gene-family CLUSTER under this sparse sampling.
"""
